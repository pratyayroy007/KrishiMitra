def get_localized_disease_info(disease_key: str, default_data: Dict[str, Any], lang: str = "en") -> Dict[str, Any]:
    """Retrieves localized disease remedies and information."""
    if lang == "en" or lang not in SUPPORTED_LANGUAGES:
        return default_data

    trans = DISEASE_TRANSLATIONS.get(disease_key, {}).get(lang)
    if not trans:
        # Fallback to English crop name translation if disease text is not fully present
        crop_en = default_data.get("crop", "")
        crop_local = CROP_TRANSLATIONS.get(crop_en, {}).get(lang, crop_en)
        res = dict(default_data)
        res["crop"] = crop_local
        return res

    result = dict(default_data)
    result["crop"] = trans.get("crop", default_data.get("crop"))
    result["condition"] = trans.get("condition", default_data.get("condition"))
    result["diagnosis"] = trans.get("diagnosis", default_data.get("diagnosis"))
    result["symptoms"] = trans.get("symptoms", default_data.get("symptoms"))
    result["treatment"] = trans.get("treatment", default_data.get("treatment"))
    result["prevention"] = trans.get("prevention", default_data.get("prevention"))
    return result


